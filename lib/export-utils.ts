// Scheduled reporting functionality
export class ScheduledReportManager {
  private schedules: Map<string, {
    id: string
    reportType: string
    frequency: 'daily' | 'weekly' | 'monthly'
    recipients: string[]
    lastRun?: Date
    nextRun: Date
  }> = new Map()

  scheduleReport(config: {
    reportType: string
    frequency: 'daily' | 'weekly' | 'monthly'
    recipients: string[]
    startDate?: Date
  }): string {
    const id = crypto.randomUUID()
    const startDate = config.startDate || new Date()
    
    let nextRun: Date
    switch (config.frequency) {
      case 'daily':
        nextRun = new Date(startDate.getTime() + 24 * 60 * 60 * 1000)
        break
      case 'weekly':
        nextRun = new Date(startDate.getTime() + 7 * 24 * 60 * 60 * 1000)
        break
      case 'monthly':
        nextRun = new Date(startDate)
        nextRun.setMonth(nextRun.getMonth() + 1)
        break
    }
    
    this.schedules.set(id, {
      id,
      reportType: config.reportType,
      frequency: config.frequency,
      recipients: config.recipients,
      nextRun
    })
    
    return id
  }

  getSchedules(): Array<{
    id: string
    reportType: string
    frequency: string
    recipients: string[]
    lastRun?: Date
    nextRun: Date
  }> {
    return Array.from(this.schedules.values())
  }

  removeSchedule(id: string): boolean {
    return this.schedules.delete(id)
  }

  // This would be called by a background job
  checkPendingReports(): Array<{
    id: string
    reportType: string
    recipients: string[]
  }> {
    const now = new Date()
    const pending = []
    
    for (const schedule of this.schedules.values()) {
      if (schedule.nextRun <= now) {
        pending.push({
          id: schedule.id,
          reportType: schedule.reportType,
          recipients: schedule.recipients
        })
      }
    }
    
    return pending
  }
}